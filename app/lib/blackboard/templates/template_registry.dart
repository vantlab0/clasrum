// ———————————————————————————————————————————————————————————————————
// Generative Drawing Registry
// ———————————————————————————————————————————————————————————————————
//
// This registry supports the Phase 4 generative AI drawing system where
// Qwen3.7-Flash creates original vector drawings from scratch.
// It is NOT a collection of predefined templates.
//
// The old built-in template catalogue has been removed. New drawings are
// generated dynamically based on lesson context, subject, and visual intent.
//
// ———————————————————————————————————————————————————————————————————

/// Registry for generative drawing protocols and references.
///
/// Supports lookup of drawing schemas, validation rules, and registered
/// drawing styles. Does not contain predefined diagram geometries.
class DrawingRegistry {
  DrawingRegistry._();

  /// Whether the registry has been initialized.
  static bool get isInitialized => _schemas.isNotEmpty || _styles.isNotEmpty;

  /// Registered drawing schemas keyed by schema ID.
  static final Map<String, DrawingSchema> _schemas = <String, DrawingSchema>{};

  /// Registered drawing styles keyed by style name.
  static final Map<String, DrawingStyle> _styles = <String, DrawingStyle>{};

  /// IDs of all registered schemas.
  static List<String> get schemaIds => _schemas.keys.toList();

  /// IDs of all registered styles.
  static List<String> get styleIds => _styles.keys.toList();

  /// Looks up a drawing schema by ID.
  static DrawingSchema? getSchema(String id) => _schemas[id];

  /// Looks up a drawing style by name.
  static DrawingStyle? getStyle(String name) => _styles[name];

  /// Registers a drawing schema.
  static void registerSchema(DrawingSchema schema) {
    _schemas[schema.id] = schema;
  }

  /// Registers a drawing style.
  static void registerStyle(DrawingStyle style) {
    _styles[style.name] = style;
  }

  /// Clears all registered schemas and styles (mainly for testing).
  static void clear() {
    _schemas.clear();
    _styles.clear();
  }

  /// Returns schemas filtered by category.
  static List<DrawingSchema> byCategory(TemplateCategory category) {
    return _schemas.values
        .where((s) => s.category == category)
        .toList(growable: false);
  }

  /// Returns styles matching [query] (case-insensitive).
  static List<DrawingStyle> searchStyles(String query) {
    final q = query.toLowerCase();
    return _styles.values
        .where((s) => s.name.toLowerCase().contains(q))
        .toList(growable: false);
  }
}

/// A drawing schema defines the structure of a generated drawing plan.
///
/// Schemas are registered by the backend and validated against model output.
/// They describe the expected drawing protocol structure without prescribing
/// the actual geometry (which is generated by the model).
class DrawingSchema {
  const DrawingSchema({
    required this.id,
    required this.name,
    required this.category,
    required this.elements,
    this.stages,
    this.metadata,
  });

  /// Unique schema identifier.
  final String id;

  /// Human-readable schema name.
  final String name;

  /// Educational category.
  final TemplateCategory category;

  /// Schema elements defining valid drawing components.
  final List<DrawingElementSchema> elements;

  /// Optional drawing stages (progressive reveal sequence).
  final List<DrawingStageSchema>? stages;

  /// Optional schema metadata.
  final Map<String, dynamic>? metadata;
}

/// An element schema defining a valid drawing component.
class DrawingElementSchema {
  const DrawingElementSchema({
    required this.id,
    required this.type,
    required this.geometry,
    this.style,
    this.defaults,
  });

  /// Element type identifier.
  final String id;

  /// Geometry type: 'line', 'path', 'rectangle', 'circle', 'text', 'highlight'.
  final String type;

  /// Geometry specification for validation.
  final DrawingGeometryGeometry geometry;

  /// Optional style configuration.
  final DrawingElementStyle? style;

  /// Optional default values for validation.
  final Map<String, dynamic>? defaults;
}

/// Geometry specification for element validation.
class DrawingGeometryGeometry {
  const DrawingGeometryGeometry({
    this.shape, // 'line', 'rect', 'circle', 'polygon'
    this.minPoints,
    this.maxPoints,
    this.requiredFields,
  });

  /// Expected shape type.
  final String? shape;

  /// Minimum number of points required.
  final int? minPoints;

  /// Maximum number of points allowed.
  final int? maxPoints;

  /// Required geometry fields.
  final List<String>? requiredFields;
}

/// Style configuration for a drawing element.
class DrawingElementStyle {
  const DrawingElementStyle({
    this.strokeColor,
    this.fillColor,
    this.strokeWidth,
    this.opacity,
  });

  /// Stroke color.
  final Color? strokeColor;

  /// Fill color.
  final Color? fillColor;

  /// Stroke width in logical pixels.
  final double? strokeWidth;

  /// Opacity (0.0 .. 1.0).
  final double? opacity;
}

/// A drawing stage defines a progressive reveal step.
class DrawingStageSchema {
  const DrawingStageSchema({
    required this.stage,
    required this.description,
    required this.elementIds,
  });

  /// Stage number (1-indexed).
  final int stage;

  /// Human-readable description.
  final String description;

  /// Element IDs that should be visible at this stage.
  final List<String> elementIds;
}

/// A drawing style defines visual properties for rendering.
class DrawingStyle {
  const DrawingStyle({
    required this.name,
    this.defaults,
  });

  /// Style name.
  final String name;

  /// Optional default values.
  final Map<String, dynamic>? defaults;
}
